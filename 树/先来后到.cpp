/*2077 年 8 月 17 日，Alice Cartalet 和 Bob在会议室焦灼地博弈，而我们的 JC 在旁边围观。

Alice突然发现自己先手必胜，她非常高兴，顺手把会议室低价出租给了一旁围观的JC，一直出租到 M时刻！

JC 灵机一动，打算转租会议室。他在时刻 0时发布通告，N 个会议预约请求应声而至！

每个会议预约都有两个重要参数 (l, r)，表示会议起止 时刻。会议室只有一间，JC 显然不能接受两个有冲突的预约。（如 (1, 5) 与 (3, 6)）

每场预约的会议都必须准时开始，也都一定会准时结束。

每场会议结束后，会议室都需要清理。因此，若上一场会议在 t 时刻结束，下一场会议最早可在 t+1时刻开始。（即 JC不能同时接受 (1, 3) 与 (3, 5)这两个预约请求）

JC向来讲武德，因此他按照先来后到的原则接受或拒绝每一个预约请求。也就是说，JC 接受当前请求 当且仅当 该请求不与先前已接受 的任何请求有时间冲突。

JC 不屑于这种重复劳动，于是他把判断每个请求能否被接受的任务交给了路过会议室的你。*/



/*思路：当当前会议室租借结束的时间+1 <= 下一次租借开始的时间时 拒绝租借*/


#include<bits/stdc++.h>
using namespace std;
int main(){
    int n,end_time;cin >> n >> end_time;
    int ddl = 0;
    for(int i=0;i<n;i++){
        int head,tail;cin >> head >> tail;
        if(head >= ddl + 1 && tail <= end_time){
            cout << "ACCEPTED" << endl;
            ddl = tail;
        }else{
            cout << "REJECTED" << endl;
        }
    }
    return 0;
}